import ts from 'typescript';
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const lines = ['# Public export inventory', '', 'Generated by `node scripts/list-exports.mjs` from built declarations. Values and types are listed separately; classes appear in both categories.', ''];
for (const name of ['ai', 'agent-core']) {
 const dir = path.join(root, 'packages', name);
 const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
 const files = Object.values(pkg.exports).map(entry => path.join(dir, entry.types));
 const program = ts.createProgram(files, { module: ts.ModuleKind.Node16, moduleResolution: ts.ModuleResolutionKind.Node16, target: ts.ScriptTarget.ES2022, skipLibCheck: true });
 const checker = program.getTypeChecker();
 for (const [subpath, entry] of Object.entries(pkg.exports)) {
  const file = program.getSourceFile(path.join(dir, entry.types));
  const symbol = file && checker.getSymbolAtLocation(file);
  if (!symbol) throw new Error(`Cannot resolve ${subpath}`);
  const values = [], types = [];
  for (const exported of checker.getExportsOfModule(symbol)) {
   const sym = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
   if (sym.flags & ts.SymbolFlags.Value) values.push(exported.name);
   if (sym.flags & ts.SymbolFlags.Type) types.push(exported.name);
  }
  lines.push(`## ${pkg.name}${subpath === '.' ? '' : subpath.slice(1)}`, '', '**Values:** ' + values.sort().map(name => '`' + name + '`').join(', '), '', '**Types:** ' + types.sort().map(name => '`' + name + '`').join(', '), '');
 }
}
fs.writeFileSync(path.join(root, 'API.md'), lines.join('\n') + '\n');
console.log('API.md: exact export inventory generated');
